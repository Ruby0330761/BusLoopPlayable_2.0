function decodeUnityInt32Hex(hex) {
  const values = [];
  for (let offset = 0; offset < hex.length; offset += 8) {
    values.push(Number.parseInt(
      `${hex.slice(offset + 6, offset + 8)}${hex.slice(offset + 4, offset + 6)}${hex.slice(offset + 2, offset + 4)}${hex.slice(offset, offset + 2)}`,
      16
    ));
  }
  return values;
}

