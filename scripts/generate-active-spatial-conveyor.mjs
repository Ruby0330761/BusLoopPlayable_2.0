import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const outputPath = path.join(root, 'src', 'generated-active-spatial-conveyor.js');
const spatialPackageRoot = path.join(root, 'artifacts', 'spatial-conveyors');
const spatialPrefix = 'spatial:';

export function getSpatialConveyorId(selection) {
  if (typeof selection !== 'string' || !selection.startsWith(spatialPrefix)) return null;
  const id = selection.slice(spatialPrefix.length);
  if (!id || !/^[A-Za-z0-9._-]+$/u.test(id) || id === '.' || id === '..') {
    throw new Error(`Invalid spatial conveyor selection: ${selection}`);
  }
  return id;
}

export function createGeneratedSpatialConveyorSource(selection, packageData = null) {
  if (packageData === null) {
    return '// Generated by scripts/generate-active-spatial-conveyor.mjs. Do not edit by hand.\n'
      + 'export const ACTIVE_SPATIAL_CONVEYOR_SELECTION = null;\n'
      + 'export const ACTIVE_SPATIAL_CONVEYOR_PACKAGE = null;\n';
  }
  const id = getSpatialConveyorId(selection);
  if (packageData?.kind !== 'spatial' || packageData.id !== id) {
    throw new Error(`Spatial conveyor package does not match selection ${selection}.`);
  }
  return '// Generated by scripts/generate-active-spatial-conveyor.mjs. Do not edit by hand.\n'
    + `export const ACTIVE_SPATIAL_CONVEYOR_SELECTION = ${JSON.stringify(selection)};\n`
    + `export const ACTIVE_SPATIAL_CONVEYOR_PACKAGE = Object.freeze(${JSON.stringify(packageData)});\n`;
}

async function generateActiveSpatialConveyor() {
  const tuningUrl = `${pathToFileURL(path.join(root, 'src', 'scene-tuning.js')).href}?t=${Date.now()}`;
  const { SCENE_TUNING } = await import(tuningUrl);
  const selection = SCENE_TUNING.conveyorLayout?.selected;
  const id = getSpatialConveyorId(selection);

  if (!id) {
    await writeFile(outputPath, createGeneratedSpatialConveyorSource(null), 'utf8');
    console.log(`Generated production conveyor selection ${selection ?? 'default'} without a spatial package.`);
    return;
  }

  const packagePath = path.join(spatialPackageRoot, `${id}.json`);
  if (!existsSync(packagePath)) {
    throw new Error(`Selected spatial conveyor package does not exist: ${path.relative(root, packagePath)}`);
  }
  const packageData = JSON.parse(await readFile(packagePath, 'utf8'));
  await writeFile(
    outputPath,
    createGeneratedSpatialConveyorSource(selection, packageData),
    'utf8'
  );
  console.log(`Generated production spatial conveyor ${selection} (${packageData.path?.points?.length ?? 0} points).`);
}

const invokedPath = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : '';
if (import.meta.url === invokedPath) {
  generateActiveSpatialConveyor().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
