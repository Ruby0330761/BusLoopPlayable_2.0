import { createHash } from 'node:crypto';

export const PLAYABLE_BUILD_CONFIG_SCHEMA_VERSION = 1;
export const PLAYABLE_PACKAGE_METADATA_ID = 'bus-loop-package-metadata';

function normalizeThreshold(value) {
  const number = Number(value);
  return Number.isFinite(number) ? Math.max(1, Math.floor(number)) : 40;
}

function normalizeVehicleExitIds(value) {
  if (Array.isArray(value)) {
    return value.map((entry) => (
      typeof entry === 'number' && Number.isFinite(entry) ? entry : String(entry)
    ));
  }
  return String(value ?? '');
}

export function createPlayableBuildConfig(tuning = {}) {
  const installGate = tuning.installGate ?? {};
  return {
    schemaVersion: PLAYABLE_BUILD_CONFIG_SCHEMA_VERSION,
    selectedLevel: String(tuning.level?.selected ?? ''),
    installGate: {
      successfulOperationThreshold: normalizeThreshold(installGate.successfulOperationThreshold),
      continueAfterStoreOpen: Boolean(installGate.continueAfterStoreOpen),
      vehicleExitGateEnabled: Boolean(installGate.vehicleExitGateEnabled),
      vehicleExitLevelKey: String(installGate.vehicleExitLevelKey ?? ''),
      vehicleExitIds: normalizeVehicleExitIds(installGate.vehicleExitIds)
    },
    retry: {
      floatingButtonEnabled: Boolean(tuning.retryButton?.enabled),
      gameOverButtonEnabled: Boolean(tuning.gameOver?.retryEnabled ?? 1)
    }
  };
}

export function createPlayableBuildSignature(config) {
  const hash = createHash('sha256')
    .update(JSON.stringify(config))
    .digest('hex');
  return `bus-loop-build-config-v${PLAYABLE_BUILD_CONFIG_SCHEMA_VERSION}:${hash}`;
}

export function createPlayablePackageMetadata(config, buildSignature) {
  return {
    ...config,
    buildSignature
  };
}

export function createGeneratedBuildConfigSource(config, buildSignature) {
  return [
    '// Generated by scripts/generate-playable-build-config.mjs. Do not edit by hand.',
    `export const PLAYABLE_BUILD_CONFIG = Object.freeze(${JSON.stringify(config, null, 2)});`,
    `export const PLAYABLE_BUILD_SIGNATURE = ${JSON.stringify(buildSignature)};`,
    ''
  ].join('\n');
}

export function injectPlayablePackageMetadata(html, metadata) {
  const json = JSON.stringify(metadata).replaceAll('<', '\\u003c');
  const source = `    <script id="${PLAYABLE_PACKAGE_METADATA_ID}" type="application/json">${json}<\/script>\n`;
  if (!html.includes('</head>')) throw new Error('Unable to inject playable package metadata.');
  return html.replace('</head>', `${source}  </head>`);
}

export function parsePlayablePackageMetadata(html) {
  const escapedId = PLAYABLE_PACKAGE_METADATA_ID.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&');
  const match = html.match(new RegExp(
    `<script\\b(?=[^>]*\\bid=["']${escapedId}["'])(?=[^>]*\\btype=["']application/json["'])[^>]*>([\\s\\S]*?)<\\/script>`,
    'iu'
  ));
  if (!match) return null;
  return JSON.parse(match[1]);
}
